export type Translations = typeof translations.ar;

const SUPPORTED_LANGUAGES: readonly Language[] = ['ar', 'en', 'fr'];

function isSupportedLanguage(value: unknown): value is Language {
  return typeof value === 'string' && (SUPPORTED_LANGUAGES as readonly string[]).includes(value);
}

export function useTranslation() {
  const [language, setLanguageState] = useState<Language>(() => {
    // Validate the stored language against a strict whitelist before
    // applying it to <html lang>/<html dir>. Prevents tampered
    // localStorage values from injecting arbitrary attribute content.
    const saved = localStorage.getItem(STORAGE_KEY);
    return isSupportedLanguage(saved) ? saved : 'ar';
  });

  const setLanguage = useCallback((lang: Language) => {
    setLanguageState(lang);
    localStorage.setItem(STORAGE_KEY, lang);
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = lang;
  }, []);

  useEffect(() => {
    document.documentElement.dir = language === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = language;
  }, [language]);

  const t = useCallback((key: keyof typeof translations.ar): string => {
    return translations[language][key] || key;
  }, [language]);

  return { t, language, setLanguage };
}
